using Dabbler.Security.Entities;

namespace Dabbler.Security.Abstractions;

/// <summary>
/// Defines an abstraction for managing multi-factor authentication (MFA) for application users,
/// including TOTP enrollment, validation, recovery, and account lockout.
/// </summary>
public interface IMfaService
{
    /// <summary>
    /// Initiates the TOTP MFA enrollment process for a user.
    /// This generates a new secret key and a URI for generating a QR code, which the user can scan
    /// with an authenticator app. The enrollment must be completed by <see cref="CompleteEnrollmentAsync"/>.
    /// </summary>
    /// <param name="userId">The unique identifier of the application user.</param>
    /// <param name="appName">The name of the application to be displayed in the authenticator app.</param>
    /// <returns>
    /// A <see cref="Task"/> that represents the asynchronous operation.
    /// The task result is a tuple containing the generated shared secret and the QR code URI.
    /// </returns>
    Task<(string Secret, string QrCodeUri)> InitiateEnrollmentAsync(int userId, string appName);

    /// <summary>
    /// Completes the TOTP MFA enrollment for a user by verifying a provided code.
    /// This method should be called after <see cref="InitiateEnrollmentAsync"/> to finalize the setup.
    /// </summary>
    /// <param name="userId">The unique identifier of the application user.</param>
    /// <param name="verificationCode">The TOTP code generated by the user's authenticator app.</param>
    /// <returns>
    /// A <see cref="Task"/> that represents the asynchronous operation.
    /// The task result is <c>true</c> if the enrollment was successfully completed, <c>false</c> otherwise.
    /// </returns>
    Task<bool> CompleteEnrollmentAsync(int userId, string verificationCode);

    /// <summary>
    /// Validates a TOTP code provided by a user. This is typically used during login
    /// or other MFA challenges.
    /// </summary>
    /// <param name="userId">The unique identifier of the application user.</param>
    /// <param name="code">The TOTP code to validate.</param>
    /// <returns>
    /// A <see cref="Task"/> that represents the asynchronous operation.
    /// The task result is <c>true</c> if the code is valid, <c>false</c> otherwise.
    /// </returns>
    Task<bool> ValidateTotpAsync(int userId, string code);

    /// <summary>
    /// Validates a recovery code provided by a user. Each recovery code can generally be used only once.
    /// </summary>
    /// <param name="userId">The unique identifier of the application user.</param>
    /// <param name="code">The recovery code to validate.</param>
    /// <returns>
    /// A <see cref="Task"/> that represents the asynchronous operation.
    /// The task result is <c>true</c> if the code is valid and successfully consumed, <c>false</c> otherwise.
    /// </returns>
    Task<bool> ValidateRecoveryCodeAsync(int userId, string code);

    /// <summary>
    /// Resets a user's MFA configuration, effectively disabling MFA for the user,
    /// revoking all existing TOTP secrets and recovery codes.
    /// </summary>
    /// <param name="userId">The unique identifier of the application user whose MFA will be reset.</param>
    /// <param name="resetByUserId">The unique identifier of the user performing the reset, for auditing purposes.</param>
    /// <returns>A <see cref="Task"/> that represents the asynchronous operation.</returns>
    Task ResetMfaAsync(int userId, int resetByUserId);

    /// <summary>
    /// Retrieves the current MFA status for a specific user.
    /// </summary>
    /// <param name="userId">The unique identifier of the application user.</param>
    /// <returns>
    /// A <see cref="Task"/> that represents the asynchronous operation.
    /// The task result contains an <see cref="AppUserMfa"/> object detailing the MFA status,
    /// or <c>null</c> if no MFA is configured for the user.
    /// </returns>
    Task<AppUserMfa?> GetMfaStatusAsync(int userId);

    /// <summary>
    /// Unlocks an account that might have been locked due to too many failed MFA attempts.
    /// </summary>
    /// <param name="userId">The unique identifier of the application user to unlock.</param>
    /// <returns>A <see cref="Task"/> that represents the asynchronous operation.</returns>
    Task UnlockAccountAsync(int userId);

    /// <summary>
    /// Generates a new set of recovery codes for a user. Any previously generated recovery codes
    /// for this user will be invalidated.
    /// </summary>
    /// <param name="userId">The unique identifier of the application user.</param>
    /// <returns>
    /// A <see cref="Task"/> that represents the asynchronous operation.
    /// The task result contains an array of newly generated recovery codes.
    /// </returns>
    Task<string[]> GenerateRecoveryCodesAsync(int userId);
}
